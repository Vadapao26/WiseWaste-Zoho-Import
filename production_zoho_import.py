import pandas as pd
import numpy as np
import openpyxl
from google.colab import files
import os

print("📂 Please upload your Production file (.xlsx or .csv):")
uploaded = files.upload()

uploaded_filename = list(uploaded.keys())[0]
print(f"✅ Successfully uploaded: {uploaded_filename}")

# 1. Load data safely (handles CSV or Excel with any sheet name)
if uploaded_filename.endswith('.csv'):
    df_raw = pd.read_csv(uploaded_filename)
else:
    xls = pd.ExcelFile(uploaded_filename)
    print(f"📑 Available sheets in workbook: {xls.sheet_names}")
    # Load the first sheet as Raw Data regardless of its tab name
    df_raw = pd.read_excel(uploaded_filename, sheet_name=xls.sheet_names[0])

# 2. Forward fill parent metadata and process equipment across multi-material sub-rows
parent_cols = [
    'S.no', 'Production Code', 'Date', 'Shift', 'Process-Equipment',
    'Time Taken (in hrs)', 'No. of Present Staffs', 'Total Rejection (in KG)',
    'Total Quantity (in KG)', 'Description'
]

existing_parent_cols = [col for col in parent_cols if col in df_raw.columns]
df_raw[existing_parent_cols] = df_raw[existing_parent_cols].ffill()

# 3. Dynamically detect all process types (e.g., Sorting, Bagging, Bailing, Shredding)
process_keywords = ['Sorting', 'Bagging', 'Bailing', 'Shredding']
detected_processes = []

if 'Process-Equipment' in df_raw.columns:
    equipment_series = df_raw['Process-Equipment'].astype(str)
    for kw in process_keywords:
        if equipment_series.str.contains(kw, case=False, na=False).any():
            detected_processes.append(kw)

# If no standard keywords found, fallback to unique equipment values or 'Production'
if not detected_processes:
    detected_processes = [str(x) for x in df_raw['Process-Equipment'].dropna().unique()]
if not detected_processes:
    detected_processes = ['Production']

print(f"🔍 Detected Process Types for Output Sheets: {detected_processes}")

# 4. Save to multi-sheet Excel workbook
output_file = "Production_Processed_MultiSheet.xlsx"

with pd.ExcelWriter(output_file, engine="openpyxl") as writer:
    for proc in detected_processes:
        # Filter rows belonging to this specific process
        proc_df = df_raw[df_raw['Process-Equipment'].str.contains(proc, case=False, na=False)].copy()

        if not proc_df.empty:
            sheet_name = f"Import Data ({proc})"
            proc_df.to_excel(writer, sheet_name=sheet_name, index=False)
            print(f"   ➕ Created sheet: '{sheet_name}' with {len(proc_df)} rows")

print("🎉 Multi-sheet processing complete!")

# 5. Auto-download the processed file
print("⬇️ Triggering automatic download...")
files.download(output_file)