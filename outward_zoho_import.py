import pandas as pd
import numpy as np
import openpyxl
import re
from google.colab import files
import os

print("📂 Please upload your Outward file (.xlsx or .csv):")
uploaded = files.upload()

uploaded_filename = list(uploaded.keys())[0]
print(f"✅ Successfully uploaded: {uploaded_filename}")

# 1. Automatically detect file type and load accordingly
if uploaded_filename.endswith('.csv'):
    df_raw = pd.read_csv(uploaded_filename)
else:
    df_raw = pd.read_excel(uploaded_filename, sheet_name="Raw Data")

# 2. Define parent columns that need forward-filling for multi-material sub-rows
parent_cols = [
    'S.no', 'Outward Code', 'Date', 'Project', 'Customer', 'Destination',
    'Address Line 1', 'Address Line 2', 'Pincode', 'City', 'State', 'Country',
    'Vehicle number', 'Transport Vendor', 'Driver Name', 'Driver Contact No',
    'Loading Cost', 'Additional Transport Cost', 'Transport Cost (in Rs)'
]

existing_parent_cols = [col for col in parent_cols if col in df_raw.columns]
df_raw[existing_parent_cols] = df_raw[existing_parent_cols].ffill()

# 3. Helper function to clean filenames/URLs and strip out any Excel formula wrappers
def extract_clean_filename(val):
    if pd.isna(val):
        return None
    val_str = str(val).strip()
    # If the cell contains an Excel HYPERLINK formula, extract just the URL inside it
    match = re.search(r'HYPERLINK\("([^"]+)"', val_str, re.IGNORECASE)
    if match:
        val_str = match.group(1)

    # If it's already a full URL, extract the final filename/path segment
    if '/' in val_str:
        val_str = val_str.split('/')[-1]

    return val_str if val_str and val_str.lower() != 'nan' else None

# 4. Define CDN Mapping & Generate Import Columns with Clean URLs
cdn_base = "https://cdn.wisewaste.in/misblobprod/1010/"

photo_mapping = {
    'GSP photo 1': ('GSP photo 1 (import)', 'vehicle_gps_photo/'),
    'GSP photo 2': ('GSP photo 2 (Import)', 'gps_photo/'),
    'Invoice': ('Invoice (Import)', 'invoice_number/'),
    'DC challan': ('DC challan (Import)', 'dc_challan/'),
    'Weighment Slip': ('Weighment Slip (import)', 'weighment_slip_file/'),
    'Vehicle and Material': ('Vehicle and Material (import)', 'vehicle_material_file/')
}

for src_col, (target_col, folder) in photo_mapping.items():
    if src_col in df_raw.columns and 'Outward Code' in df_raw.columns:
        # Clean each filename first
        cleaned_files = df_raw[src_col].apply(extract_clean_filename)

        # Construct the clean, absolute URL
        df_raw[target_col] = np.where(
            cleaned_files.notna(),
            cdn_base + folder + df_raw['Outward Code'].astype(str) + '/' + cleaned_files,
            None
        )

# 5. Save to Excel using openpyxl
output_file = "Outward_Zoho_Ready.xlsx"
df_raw.to_excel(output_file, sheet_name="Import Data", index=False)

# 6. Post-process with openpyxl to inject calculation formulas
wb = openpyxl.load_workbook(output_file)
ws = wb["Import Data"]

headers = [cell.value for cell in ws[1]]
col_map = {name: idx + 1 for idx, name in enumerate(headers) if name}

for r in range(2, ws.max_row + 1):
    if 'Total Accepted Qty (in KG)' in col_map:
        ws.cell(row=r, column=col_map['Total Accepted Qty (in KG)']).value = f"=V{r}-Y{r}"
    if 'Value of Accepted Material (in Rs)' in col_map:
        ws.cell(row=r, column=col_map['Value of Accepted Material (in Rs)']).value = f"=Z{r}*W{r}"
    if 'Rejection %' in col_map:
        ws.cell(row=r, column=col_map['Rejection %']).value = f"=Y{r}/V{r}"
    if 'Total Dispatched Qty (in KG)' in col_map:
        ws.cell(row=r, column=col_map['Total Dispatched Qty (in KG)']).value = f"=V{r}"
    if 'Total value of dispatched materials (in Rs)' in col_map:
        ws.cell(row=r, column=col_map['Total value of dispatched materials (in Rs)']).value = f"=V{r}*W{r}"
    if 'Total Value of accepted qty (in Rs)' in col_map:
        ws.cell(row=r, column=col_map['Total Value of accepted qty (in Rs)']).value = f"=AA{r}"

wb.save(output_file)
print("🎉 Processing complete! Clean URLs generated for Zoho without formula wrappers.")

# 7. Auto-download the processed file
print("⬇️ Triggering automatic download...")
files.download(output_file)