from google.colab import files
import pandas as pd
import numpy as np
import openpyxl
import re
import urllib.parse
import os

print("📂 Please upload your file(s) (Inward, Production, Outward, Expense, Revenue, Training):")
uploaded = files.upload()

cdn_base = "https://cdn.wisewaste.in/misblobprod/1010/"

def extract_clean_filename(val):
    if pd.isna(val):
        return None
    val_str = str(val).strip()
    match = re.search(r'HYPERLINK\("([^"]+)"', val_str, re.IGNORECASE)
    if match:
        val_str = match.group(1)
    if '/' in val_str:
        val_str = val_str.split('/')[-1]
    return val_str if val_str and val_str.lower() != 'nan' else None

for uploaded_filename in uploaded.keys():
    print(f"\n🔄 Processing: {uploaded_filename}...")
    lower_name = uploaded_filename.lower()
    base_name = os.path.splitext(uploaded_filename)[0]

    # Clean up trailing numbers from duplicate uploads like "Revenue (1)" -> "Revenue"
    base_name = re.sub(r'\s*\(\d+\)$', '', base_name)
    output_filename = f"{base_name} ZOHO Import.xlsx"

    # --- 1. INWARD ---
    if 'inward' in lower_name:
        df_raw = pd.read_csv(uploaded_filename) if uploaded_filename.endswith('.csv') else pd.read_excel(uploaded_filename, sheet_name=0)

        parent_cols = ['S.no', 'Inward Code', 'Date', 'Received material from', 'Vendor Location', 'Source', 'Project name', 'Vehicle Number', 'Loading Cost', 'Driver Name', 'Vehicle Vendor Name', 'Transportation Cost (in Rs)', 'Additional Cost (in Rs)', 'Total Tax (in %)']
        existing_parent_cols = [col for col in parent_cols if col in df_raw.columns]
        df_raw[existing_parent_cols] = df_raw[existing_parent_cols].ffill()

        inward_mapping = {
            'Vendor Invoice': ('Vendor Invoice (import)', 'vendor_invoice/'),
            'Weighment Slip': ('Weighment Slip (import)', 'weighment_slip_file/'),
            'Vehicle GPS Photo': ('Vehicle GPS Photo (Import)', 'vehicle_gps_photo/'),
            'Delivery Challan': ('Delivery Challan (import)', 'inward_record/'),
            'Material GPS Photo': ('Material GPS Photo (import)', 'material_gps/')
        }
        for src_col, (target_col, folder) in inward_mapping.items():
            if src_col in df_raw.columns and 'Inward Code' in df_raw.columns:
                cleaned = df_raw[src_col].apply(extract_clean_filename)
                df_raw[target_col] = np.where(cleaned.notna(), cdn_base + folder + df_raw['Inward Code'].astype(str) + '/' + cleaned.apply(lambda x: urllib.parse.quote(str(x), safe='')), None)

        df_raw.to_excel(output_filename, sheet_name="Import Data", index=False)

        wb = openpyxl.load_workbook(output_filename)
        ws = wb["Import Data"]
        col_map = {cell.value: idx + 1 for idx, cell in enumerate(ws[1]) if cell.value}
        for r in range(2, ws.max_row + 1):
            if 'Accepted Billed Qty (in KG)' in col_map: ws.cell(row=r, column=col_map['Accepted Billed Qty (in KG)']).value = f"=P{r}-S{r}"
            if 'Value of Accepted Qty (in Rs)' in col_map: ws.cell(row=r, column=col_map['Value of Accepted Qty (in Rs)']).value = f"=U{r}*Q{r}"
            if 'Total Received Qty (in KG)' in col_map: ws.cell(row=r, column=col_map['Total Received Qty (in KG)']).value = f"=P{r}"
            if 'Total Accepted Qty (in KG)' in col_map: ws.cell(row=r, column=col_map['Total Accepted Qty (in KG)']).value = f"=P{r}-S{r}"
            if 'Total Rejected Qty (in KG)' in col_map: ws.cell(row=r, column=col_map['Total Rejected Qty (in KG)']).value = f"=S{r}"
            if 'Total Amount (in Rs)' in col_map: ws.cell(row=r, column=col_map['Total Amount (in Rs)']).value = f"=R{r}"
        wb.save(output_filename)

    # --- 2. OUTWARD ---
    elif 'outward' in lower_name:
        df_raw = pd.read_csv(uploaded_filename) if uploaded_filename.endswith('.csv') else pd.read_excel(uploaded_filename, sheet_name=0)

        parent_cols = ['S.no', 'Outward Code', 'Date', 'Project', 'Customer', 'Destination', 'Address Line 1', 'Address Line 2', 'Pincode', 'City', 'State', 'Country', 'Vehicle number', 'Transport Vendor', 'Driver Name', 'Driver Contact No', 'Loading Cost', 'Additional Transport Cost', 'Transport Cost (in Rs)']
        existing_parent_cols = [col for col in parent_cols if col in df_raw.columns]
        df_raw[existing_parent_cols] = df_raw[existing_parent_cols].ffill()

        outward_mapping = {
            'GSP photo 1': ('GSP photo 1 (import)', 'vehicle_gps_photo/'),
            'GSP photo 2': ('GSP photo 2 (Import)', 'gps_photo/'),
            'Invoice': ('Invoice (Import)', 'invoice_number/'),
            'DC challan': ('DC challan (Import)', 'dc_challan/'),
            'Weighment Slip': ('Weighment Slip (import)', 'weighment_slip_file/'),
            'Vehicle and Material': ('Vehicle and Material (import)', 'vehicle_material_file/')
        }
        for src_col, (target_col, folder) in outward_mapping.items():
            if src_col in df_raw.columns and 'Outward Code' in df_raw.columns:
                cleaned = df_raw[src_col].apply(extract_clean_filename)
                df_raw[target_col] = np.where(cleaned.notna(), cdn_base + folder + df_raw['Outward Code'].astype(str) + '/' + cleaned.apply(lambda x: urllib.parse.quote(str(x), safe='')), None)

        df_raw.to_excel(output_filename, sheet_name="Import Data", index=False)

        wb = openpyxl.load_workbook(output_filename)
        ws = wb["Import Data"]
        col_map = {cell.value: idx + 1 for idx, cell in enumerate(ws[1]) if cell.value}
        for r in range(2, ws.max_row + 1):
            if 'Total Accepted Qty (in KG)' in col_map: ws.cell(row=r, column=col_map['Total Accepted Qty (in KG)']).value = f"=V{r}-Y{r}"
            if 'Value of Accepted Material (in Rs)' in col_map: ws.cell(row=r, column=col_map['Value of Accepted Material (in Rs)']).value = f"=Z{r}*W{r}"
            if 'Rejection %' in col_map: ws.cell(row=r, column=col_map['Rejection %']).value = f"=Y{r}/V{r}"
            if 'Total Dispatched Qty (in KG)' in col_map: ws.cell(row=r, column=col_map['Total Dispatched Qty (in KG)']).value = f"=V{r}"
            if 'Total value of dispatched materials (in Rs)' in col_map: ws.cell(row=r, column=col_map['Total value of dispatched materials (in Rs)']).value = f"=V{r}*W{r}"
            if 'Total Value of accepted qty (in Rs)' in col_map: ws.cell(row=r, column=col_map['Total Value of accepted qty (in Rs)']).value = f"=AA{r}"
        wb.save(output_filename)

    # --- 3. PRODUCTION ---
    elif 'production' in lower_name:
        df_raw = pd.read_csv(uploaded_filename) if uploaded_filename.endswith('.csv') else pd.read_excel(uploaded_filename, sheet_name=0)

        parent_cols = ['S.no', 'Production Code', 'Date', 'Shift', 'Process-Equipment', 'Time Taken (in hrs)', 'No. of Present Staffs', 'Total Rejection (in KG)', 'Total Quantity (in KG)', 'Description']
        existing_parent_cols = [col for col in parent_cols if col in df_raw.columns]
        df_raw[existing_parent_cols] = df_raw[existing_parent_cols].ffill()

        process_keywords = ['Sorting', 'Bagging', 'Bailing', 'Shredding']
        detected_processes = [kw for kw in process_keywords if 'Process-Equipment' in df_raw.columns and df_raw['Process-Equipment'].astype(str).str.contains(kw, case=False, na=False).any()]
        if not detected_processes: detected_processes = ['Production']

        with pd.ExcelWriter(output_filename, engine="openpyxl") as writer:
            for proc in detected_processes:
                proc_df = df_raw[df_raw['Process-Equipment'].str.contains(proc, case=False, na=False)].copy() if 'Process-Equipment' in df_raw.columns else df_raw.copy()
                if not proc_df.empty:
                    proc_df.to_excel(writer, sheet_name=f"Import Data ({proc})", index=False)

    # --- 4. REVENUE ---
    elif 'revenue' in lower_name:
        df_rev = pd.read_csv(uploaded_filename) if uploaded_filename.endswith('.csv') else pd.read_excel(uploaded_filename, sheet_name=0)
        if 'Revenue Code' in df_rev.columns and 'Upload Bill' in df_rev.columns:
            cleaned = df_rev['Upload Bill'].apply(extract_clean_filename)
            df_rev['Upload Bill (import)'] = np.where(cleaned.notna(), cdn_base + "revenue_agreement/" + df_rev['Revenue Code'].astype(str) + '/' + cleaned.apply(lambda x: urllib.parse.quote(str(x), safe='')), None)
        df_rev.to_excel(output_filename, sheet_name="Import Data", index=False)

    # --- 5. EXPENSE ---
    elif 'expense' in lower_name:
        df_exp = pd.read_csv(uploaded_filename) if uploaded_filename.endswith('.csv') else pd.read_excel(uploaded_filename, sheet_name=0)
        if 'Expense Code' in df_exp.columns and 'Upload Bill' in df_exp.columns:
            cleaned = df_exp['Upload Bill'].apply(extract_clean_filename)
            df_exp['Upload Bill (import)'] = np.where(cleaned.notna(), cdn_base + "expense_agreement/" + df_exp['Expense Code'].astype(str) + '/' + cleaned.apply(lambda x: urllib.parse.quote(str(x), safe='')), None)
        df_exp.to_excel(output_filename, sheet_name="Import Data", index=False)

    # --- 6. TRAINING ---
    elif 'training' in lower_name:
        df_train = pd.read_csv(uploaded_filename) if uploaded_filename.endswith('.csv') else pd.read_excel(uploaded_filename, sheet_name=0)
        training_cols = [
            'Training Photo 1', 'Training Photo 2', 'Feedback Report',
            'Module File', 'Pre-Assessment File', 'Post-Assessment File', 'Acknowledgement File'
        ]
        if 'Training Code' in df_train.columns:
            for col in training_cols:
                if col in df_train.columns:
                    cleaned = df_train[col].apply(extract_clean_filename)
                    df_train[f"{col} (import)"] = np.where(
                        cleaned.notna(),
                        cdn_base + "training_agreement/" + df_train['Training Code'].astype(str) + '/' + cleaned.apply(lambda x: urllib.parse.quote(str(x), safe='')),
                        None
                    )
        df_train.to_excel(output_filename, sheet_name="Import Data", index=False)

    print(f"✅ Successfully processed and downloaded: {output_filename}")
    files.download(output_filename)

print("\n🎉 All uploaded files processed and downloaded successfully!")